"""Regenerate THIRD_PARTY_NOTICES.md and THIRD_PARTY_LICENSES.txt.

THIRD_PARTY_NOTICES.md lists every Rust crate and bundled npm package with its
license. THIRD_PARTY_LICENSES.txt collects the license and notice files that
ship inside those packages (identical texts are listed once). Both files are
bundled with the installer.

Usage: python scripts/third_party_notices.py
"""
import hashlib
import json
import os
import subprocess

LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "unlicense")


def license_files(directory):
    """License-like files at the top of a package directory."""
    try:
        names = sorted(os.listdir(directory))
    except OSError:
        return []
    found = []
    for name in names:
        path = os.path.join(directory, name)
        if os.path.isfile(path) and name.lower().startswith(LICENSE_PREFIXES):
            found.append(path)
    return found


def read_text(path):
    with open(path, "rb") as f:
        return f.read().decode("utf-8", errors="replace").replace("\r\n", "\n").strip()


meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"]))
ids = {n["id"] for n in meta["resolve"]["nodes"]}
pkgs = sorted((p for p in meta["packages"] if p["id"] in ids and p["source"]),
              key=lambda p: (p["name"], p["version"]))

lines = [
    "# Third-party notices",
    "",
    "Fetchlane's own code is MIT-licensed (see `LICENSE`). Builds include the Rust crates",
    "and npm packages listed below, each under its own license. The license and notice",
    "files shipped with them are collected in `THIRD_PARTY_LICENSES.txt`, which is",
    "installed with Fetchlane next to this file.",
    "",
    "MPL-2.0 crates are used unmodified; their source is available from the linked repositories.",
    "",
    "Generated by `scripts/third_party_notices.py` for the Windows x64 target. The list",
    "errs on the side of completeness: it includes build-time and test-only crates.",
    "",
    "| Crate | Version | License | Repository |",
    "| --- | --- | --- | --- |",
]
# text hash -> (text, [package labels])
texts = {}
missing = []


def collect(label, directory, declared):
    files = license_files(directory)
    if not files:
        missing.append(f"{label} ({declared})")
        return
    for path in files:
        text = read_text(path)
        if not text:
            continue
        key = hashlib.sha256(text.encode("utf-8")).hexdigest()
        texts.setdefault(key, (text, []))[1].append(f"{label}: {os.path.basename(path)}")


for p in pkgs:
    lic = p.get("license") or "see crate"
    lines.append(f"| {p['name']} | {p['version']} | {lic} | {p.get('repository') or ''} |")
    collect(f"{p['name']} {p['version']}", os.path.dirname(p["manifest_path"]), lic)

# npm packages bundled into the UI (dev-only tools such as Vite are excluded).
lock = json.load(open("package-lock.json", encoding="utf-8"))
npm = sorted(
    (path, path.split("node_modules/")[-1], info)
    for path, info in lock.get("packages", {}).items()
    if path.startswith("node_modules/") and not info.get("dev") and not info.get("devOptional")
)
lines += [
    "",
    "## npm packages bundled into the UI",
    "",
    "| Package | Version | License |",
    "| --- | --- | --- |",
]
for path, name, info in npm:
    lic = info.get("license", "see package")
    lines.append(f"| {name} | {info.get('version', '')} | {lic} |")
    collect(f"{name} {info.get('version', '')} (npm)", path, lic)

if missing:
    lines += [
        "",
        "## Packages without a license file",
        "",
        "These packages declare their license in their metadata but don't ship a license",
        "file. The standard text of each license named here is included in",
        "`THIRD_PARTY_LICENSES.txt` from other packages under the same license; their",
        "repositories have their copyright notices.",
        "",
    ]
    lines += [f"- {m}" for m in missing]

open("THIRD_PARTY_NOTICES.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")

out = [
    "Third-party license texts for Fetchlane",
    "=======================================",
    "",
    "The license and notice files shipped with the Rust crates and npm packages",
    "listed in THIRD_PARTY_NOTICES.md. Identical texts appear once, followed by the",
    "packages they come from.",
]
for text, owners in sorted(texts.values(), key=lambda t: t[1][0].lower()):
    out += ["", "-" * 78, ""]
    out += [f"Used by: {o}" for o in owners]
    out += ["", text]
open("THIRD_PARTY_LICENSES.txt", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"{len(pkgs)} crates, {len(npm)} npm packages, {len(texts)} distinct license texts, "
      f"{len(missing)} without a license file")
