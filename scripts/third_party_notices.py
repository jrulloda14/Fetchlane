"""Regenerate THIRD_PARTY_NOTICES.md from `cargo metadata`.

Usage: python scripts/third_party_notices.py
"""
import json
import subprocess

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"]))
ids = {n["id"] for n in meta["resolve"]["nodes"]}
pkgs = sorted((p for p in meta["packages"] if p["id"] in ids and p["source"]),
              key=lambda p: (p["name"], p["version"]))

lines = [
    "# Third-party notices",
    "",
    "Fetchlane's own code is MIT-licensed (see `LICENSE`). Builds include the Rust crates",
    "listed below, each under its own license. Full license texts are in each crate's",
    "source distribution (see `~/.cargo/registry/src` or crates.io).",
    "",
    "MPL-2.0 crates are used unmodified; their source is available from the linked repositories.",
    "",
    "Generated by `scripts/third_party_notices.py` for the Windows x64 target.",
    "",
    "| Crate | Version | License | Repository |",
    "| --- | --- | --- | --- |",
]
for p in pkgs:
    lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see crate'} | {p.get('repository') or ''} |")
open("THIRD_PARTY_NOTICES.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(pkgs)} crates")
